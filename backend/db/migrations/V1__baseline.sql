-- V1: baseline schema for the Notes app.
--
-- Recreates the schema the app used on SQLite (tables, keys, constraints and
-- indexes), translated to PostgreSQL types and snake_case names. Schema only:
-- no data. From now on Flyway owns the schema; TypeORM only maps these tables
-- to entities (synchronize is off). Change the schema with a new V<n>__*.sql
-- file, never by editing this one.
--
-- Constraint and index names follow the convention the backend's TypeORM
-- naming strategy expects (src/database/naming.strategy.ts):
--   pk_<table>, uq_<table>_<columns>, fk_<table>_<columns>, idx_<table>_<columns>

CREATE TABLE users (
    id            integer GENERATED BY DEFAULT AS IDENTITY,
    username      varchar     NOT NULL,
    password_hash varchar     NOT NULL,
    created_at    timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT pk_users PRIMARY KEY (id),
    CONSTRAINT uq_users_username UNIQUE (username)
);

CREATE TABLE categories (
    id      integer GENERATED BY DEFAULT AS IDENTITY,
    name    varchar NOT NULL,
    user_id integer NOT NULL,
    CONSTRAINT pk_categories PRIMARY KEY (id),
    -- Category names are unique per user (case-sensitive, as before).
    CONSTRAINT uq_categories_name_user_id UNIQUE (user_id, name),
    CONSTRAINT fk_categories_user_id FOREIGN KEY (user_id)
        REFERENCES users (id) ON DELETE CASCADE
);

CREATE TABLE notes (
    id         integer GENERATED BY DEFAULT AS IDENTITY,
    title      varchar(200) NOT NULL,
    content    text         NOT NULL DEFAULT '',
    archived   boolean      NOT NULL DEFAULT false,
    created_at timestamptz  NOT NULL DEFAULT now(),
    updated_at timestamptz  NOT NULL DEFAULT now(),
    user_id    integer      NOT NULL,
    CONSTRAINT pk_notes PRIMARY KEY (id),
    CONSTRAINT fk_notes_user_id FOREIGN KEY (user_id)
        REFERENCES users (id) ON DELETE CASCADE
);

-- Join table for the Note <-> Category many-to-many relation.
CREATE TABLE note_categories (
    note_id     integer NOT NULL,
    category_id integer NOT NULL,
    CONSTRAINT pk_note_categories PRIMARY KEY (note_id, category_id),
    CONSTRAINT fk_note_categories_note_id FOREIGN KEY (note_id)
        REFERENCES notes (id) ON DELETE CASCADE ON UPDATE CASCADE,
    -- NO ACTION, as on SQLite: the app removes the links before deleting a category.
    CONSTRAINT fk_note_categories_category_id FOREIGN KEY (category_id)
        REFERENCES categories (id)
);

CREATE INDEX idx_note_categories_note_id ON note_categories (note_id);
CREATE INDEX idx_note_categories_category_id ON note_categories (category_id);
